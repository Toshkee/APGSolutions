// Generates the dotted map of the lower 48 states used by the coverage section.
// Run after changing cities or density:  node scripts/make-us-map.mjs
// Writes public/apg/us-dots.svg (the dots, as one static image) and src/content/us-map.ts (coordinates for the routes).
import DottedMap from "dotted-map";
import { writeFileSync } from "node:fs";

// Nashville is the hub; routes go out to these cities (spread so the whole country is covered)
const hub = { name: "Nashville, TN", lat: 36.16, lng: -86.78 };
const cities = [
  { name: "Seattle", lat: 47.61, lng: -122.33 },
  { name: "Los Angeles", lat: 34.05, lng: -118.24 },
  { name: "Phoenix", lat: 33.45, lng: -112.07 },
  { name: "Salt Lake City", lat: 40.76, lng: -111.89 },
  { name: "Denver", lat: 39.74, lng: -104.99 },
  { name: "Dallas", lat: 32.78, lng: -96.8 },
  { name: "Minneapolis", lat: 44.98, lng: -93.27 },
  { name: "Chicago", lat: 41.88, lng: -87.63 },
  { name: "Atlanta", lat: 33.75, lng: -84.39 },
  { name: "Miami", lat: 25.76, lng: -80.19 },
  { name: "New York", lat: 40.71, lng: -74.0 },
];

const options = {
  height: 44,
  grid: "diagonal",
  countries: ["USA"],
  // lower 48 only (drops Alaska and Hawaii)
  region: { lat: { min: 24.3, max: 49.5 }, lng: { min: -125, max: -66.8 } },
};

// 1) the dots image, without pins
const map = new DottedMap(options);
const svg = map.getSVG({ radius: 0.22, color: "#5d77b8", shape: "circle", backgroundColor: "transparent" });
const viewBox = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
writeFileSync("public/apg/us-dots.svg", svg);

// 2) where each city lands on that grid
const pinned = new DottedMap(options);
for (const c of [hub, ...cities]) pinned.addPin({ lat: c.lat, lng: c.lng, data: c.name });
const at = Object.fromEntries(pinned.getPoints().filter((p) => p.data).map((p) => [p.data, { x: +p.x.toFixed(2), y: +p.y.toFixed(2) }]));

const ts = `// Generated by scripts/make-us-map.mjs — don't edit by hand, change the script and run it again.
export const usMap = {
  width: ${viewBox[1]},
  height: ${viewBox[2]},
  hub: ${JSON.stringify({ name: hub.name, ...at[hub.name] })},
  cities: ${JSON.stringify(cities.map((c) => ({ name: c.name, ...at[c.name] })), null, 2).replace(/\n/g, "\n  ")},
};
`;
writeFileSync("src/content/us-map.ts", ts);
console.log(`dots: ${(svg.length / 1024).toFixed(0)} KB, viewBox ${viewBox[1]}x${viewBox[2]}, ${Object.keys(at).length} pins`);
